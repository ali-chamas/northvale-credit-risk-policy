def check(spec: dict) -> list[str]:
    errs = []

    def chk(i, what, s, n):
        if s is not None and len(s) > n:
            errs.append(f"slide {i + 1} {what}: {len(s)} > {n} chars: {s}")

    n = len(spec["slides"])
    if not 10 <= n <= 12:
        errs.append(f"deck has {n} slides; 10-12 required")
    for i, s in enumerate(spec["slides"]):
        t, lim = s["type"], LIMITS[s["type"]]
        chk(i, "title", s["title"], lim["title"])
        if s["title"].endswith("."):
            errs.append(f"slide {i + 1}: title ends with a full stop")
        notes = s.get("notes", "")
        if notes and not 60 <= len(notes.split()) <= 120:
            errs.append(f"slide {i + 1}: notes have {len(notes.split())} words (60-120)")
        if t == "title":
            chk(i, "subtitle", s["subtitle"], lim["subtitle"])
        elif t == "finding":
            chk(i, "stat value", s["stat"]["value"], lim["stat_value"])
            chk(i, "stat label", s["stat"]["label"], lim["stat_label"])
            chk(i, "source", s.get("source"), lim["source"])
            for b in s["bullets"]:
                chk(i, "bullet", b, lim["bullets"])
        elif t == "two_charts":
            for im in s["images"]:
                chk(i, "caption", im["caption"], lim["caption"])
        elif t == "stats":
            chk(i, "lead", s.get("lead"), lim["lead"])
            for st in s["stats"]:
                chk(i, "stat label", st["label"], lim["label"])
                chk(i, "stat note", st["note"], lim["note"])
        elif t == "steps":
            for st in s["steps"]:
                chk(i, "step title", st["title"], lim["step_title"])
                chk(i, "step text", st["text"], lim["step_text"])
        elif t == "cards":
            for c in s["cards"]:
                chk(i, "card title", c["title"], lim["card_title"])
                chk(i, "card text", c["text"], lim["card_text"])
                chk(i, "card meta", c["meta"], lim["meta"])
        elif t == "columns":
            for col in s["columns"]:
                for b in col["bullets"]:
                    chk(i, "bullet", b, lim["bullet"])
        elif t == "text":
            for sec in s["sections"]:
                chk(i, "section", sec["text"], lim["section"])
    return errs


def main() -> None:
    m = json.loads(C.METRICS.read_text())
    spec = build(m)
    errs = check(spec)
    if errs:
        raise SystemExit("deck_content: length limits broken\n" + "\n".join(errs))
    out = C.ROOT / "deck" / "deck_spec.json"
    out.write_text(json.dumps(spec, indent=2, ensure_ascii=False) + "\n")
    print(f"deck_content: wrote {out.relative_to(C.ROOT)} ({len(spec['slides'])} slides)")


if __name__ == "__main__":
    main()
