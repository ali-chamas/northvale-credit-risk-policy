def usd(v, short=True):
    return money(v, cur="$", short=short)


def signed_usd(v):
    return ("+" if v >= 0 else "") + usd(v)


def val(example: dict, feature: str) -> float:
    return next(t["value"] for t in example["top"] if t["feature"] == feature)


